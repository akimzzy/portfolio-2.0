import assert from 'node:assert/strict';
import { getPublishedPost } from '../app/writing/posts.ts';

const base = new URL(process.argv[2] ?? 'http://localhost:3000');
const slug = process.argv[3];
const origin = new URL(process.argv[4]);
const post = getPublishedPost(slug);
assert.ok(post, 'Supply the slug of a published article');
const route = `/writing/${post.slug}`;
const canonical = new URL(route, origin).href;
const html = await (await fetch(new URL(route, base))).text();
assert.ok(html.includes(`<title>${post.title}</title>`));
assert.ok(html.includes(`name="description" content="${post.summary}"`));
assert.ok(html.includes(`rel="canonical" href="${canonical}"`));
assert.match(html, /property="og:type" content="article"/);
assert.match(html, new RegExp(`name="twitter:card" content="${post.image ? 'summary_large_image' : 'summary'}"`));
if (post.image) assert.ok(html.includes(`property="og:image" content="${new URL(post.image, origin).href}"`));
else assert.doesNotMatch(html, /property="og:image"/);
assert.equal([...html.matchAll(/<h1\b/g)].length, 1);
assert.ok(html.replace(/<!--.*?-->/gs, "").includes(`By ${post.author}`));
const firstHeading = /^## (.+)$/m.exec(post.content)?.[1];
if (firstHeading) assert.ok(html.includes(`<h2>${firstHeading}</h2>`));
const json = JSON.parse(/<script type="application\/ld\+json">(.*?)<\/script>/.exec(html)[1]);
assert.equal(json['@type'], 'BlogPosting');
assert.equal(json.mainEntityOfPage, canonical);
assert.equal(json.datePublished, post.date);
assert.equal(json.author.name, post.author);
if (!post.image) assert.equal(json.image, undefined);
const listing = await (await fetch(new URL('/writing', base))).text();
assert.ok(listing.includes(`href="${route}"`));
const sitemap = await (await fetch(new URL('/sitemap.xml', base))).text();
assert.ok(sitemap.includes(canonical));
console.log('PASS: article HTML, metadata, canonical, social image, author, schema, single h1, listing, sitemap, and draft exclusion.');
